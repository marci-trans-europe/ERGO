export const classifyProduct = (
  itemNumber: string,
  itemName: string,
): ProductClassification => {
  const name = itemName.trim()
  const code = itemNumber.trim()
  const manufacturer = manufacturerFor(name, code)

  if (!code && name === '(nincs megnevezés)') {
    return { category: 'Szakmai szolgáltatások és díjak', manufacturer, kind: 'service' }
  }

  if (/(?:^|[^a-z0-9])mdf(?:$|[^a-z0-9])/i.test(code) || /\b(mdf|marketing development fund|movink product launch|see fy\d+|product launch event|promotion claiming amount|pr kommunikációs)\b/i.test(name)) {
    return { category: 'Marketing fund', manufacturer, kind: 'marketing-fund' }
  }
  if (/\b(commission cost|reseller commission|rebate|jutalék|partner sales incentive)\b/i.test(name)) {
    return {
      category: /\bautodesk\b/i.test(name) || /^AUTODESK_COSMM_COST$/i.test(code)
        ? 'Mérnöki és CAD'
        : 'Szakmai szolgáltatások és díjak',
      manufacturer,
      kind: 'rebate',
    }
  }
  if (/(on-site professional services|professional service|consulting service|tanácsadási szolgáltatás|helyszíni szolgáltatás|shipping and handling|előlegszámla|elõlegszámla|előlegfizetés|távfelügyeleti díj|gépkocsi magánh|szoftver szaktanácsadás)/i.test(name)) {
    return { category: 'Szakmai szolgáltatások és díjak', manufacturer, kind: 'service' }
  }
  if (/^pf_/i.test(code)) {
    return { category: 'Mérnöki és CAD', manufacturer, kind: 'product' }
  }
  const category = rules.find(([, pattern]) => pattern.test(name))?.[0]
    ?? vendorCategories[manufacturer]
    ?? 'Szakmai üzleti alkalmazások'
  return { category, manufacturer, kind: 'product' }
}
